import fs from 'node:fs';
import path from 'node:path';
import {registerHooks} from 'node:module';
registerHooks({resolve(s,c,n){return c.parentURL?.includes('/web/src/')&&s.startsWith('.')&&!path.extname(s)?n(s+'.ts',c):n(s,c);}});
const {secureMemwalClient}=await import('../src/lib/memwal-secure.ts');
const client=await secureMemwalClient();
const page=await client.listMemories({namespace:process.env.MEMWAL_NAMESPACE||'incident-memory-v1',limit:100});
const job=await client.getRememberStatus('edfdbf0f-931b-464f-a5e7-f009de08498c');
const result={checkedAt:new Date().toISOString(),memoryWrites:0,statuses:page.memories.map(m=>({status:m.status,hasBlob:!!m.blob_id})),completedJob:{jobId:job.job_id,status:job.status,blobId:job.blob_id,namespace:job.namespace}};
fs.mkdirSync('../evidence/phase14',{recursive:true});
fs.writeFileSync('../evidence/phase14/storage-readonly.json',JSON.stringify(result,null,2)+'\n');
console.log(JSON.stringify(result));
